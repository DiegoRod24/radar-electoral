alter table public.profiles enable row level security;
alter table public.runs enable row level security;
alter table public.parties enable row level security;
alter table public.assignments enable row level security;
alter table public.ads enable row level security;
alter table public.evidence_files enable row level security;
alter table public.audit_log enable row level security;

-- Primera política básica: los datos marcados PUBLICADOS serán visibles sin login.
drop policy if exists "public can read published ads" on public.ads;
create policy "public can read published ads" on public.ads
for select using (published = true);

drop policy if exists "public can read active parties" on public.parties;
create policy "public can read active parties" on public.parties
for select using (active = true);

